"""Data loading, ID translation, CIF parsing, and PyTorch Dataset for AFDB."""

import os
import re
from pathlib import Path
from typing import List, Tuple, Optional, Dict, Any
import numpy as np

# Standard 20 canonical amino acids + unknown + padding
AMINO_ACIDS = "ACDEFGHIKLMNPQRSTVWY"
AA_TO_ID = {aa: i for i, aa in enumerate(AMINO_ACIDS)}
AA_TO_ID["X"] = 20
AA_TO_ID["<pad>"] = 21

ID_TO_AA = {i: aa for aa, i in AA_TO_ID.items()}
VOCAB_SIZE = len(AA_TO_ID)
PAD_IDX = AA_TO_ID["<pad>"]

CANONICAL_THREE_TO_ONE = {
    'ALA': 'A', 'CYS': 'C', 'ASP': 'D', 'GLU': 'E', 'PHE': 'F',
    'GLY': 'G', 'HIS': 'H', 'ILE': 'I', 'LYS': 'K', 'LEU': 'L',
    'MET': 'M', 'ASN': 'N', 'PRO': 'P', 'GLN': 'Q', 'ARG': 'R',
    'SER': 'S', 'THR': 'T', 'VAL': 'V', 'TRP': 'W', 'TYR': 'Y'
}
ONE_TO_THREE = {v: k for k, v in CANONICAL_THREE_TO_ONE.items()}
ONE_TO_THREE['X'] = 'UNK'

THREE_TO_ONE = dict(CANONICAL_THREE_TO_ONE)
THREE_TO_ONE.update({'SEC': 'C', 'MSE': 'M'})


def af_id_to_url(protein_id: str) -> Optional[str]:
    """Convert an RCSB entity ID (e.g. AF_AFQ5V1K0F1_1) to an AlphaFold EBI CIF download URL."""
    m = re.match(r"AF_AF(.+?)(F\d+)_\d+$", protein_id.strip())
    if not m:
        return None
    uniprot_id = m.group(1)
    fragment_id = m.group(2)
    return f"https://alphafold.ebi.ac.uk/files/AF-{uniprot_id}-{fragment_id}-model_v6.cif"


def af_id_to_filename(protein_id: str) -> Optional[str]:
    """Convert an RCSB entity ID to its corresponding CIF filename."""
    m = re.match(r"AF_AF(.+?)(F\d+)_\d+$", protein_id.strip())
    if not m:
        return None
    return f"AF-{m.group(1)}-{m.group(2)}-model_v6.cif"


def load_split(split: str, splits_dir: str = "data/splits", suffix: str = "") -> List[str]:
    """Load protein IDs for a given split ('train', 'eval', 'test')."""
    candidates = [
        Path(splits_dir) / f"{split}_af{suffix}.txt",
        Path(f"{split}_af{suffix}.txt"),
        Path(f"data/splits/{split}_af{suffix}.txt"),
    ]
    for p in candidates:
        if p.exists():
            with open(p, "r") as f:
                return [line.strip() for line in f if line.strip()]
    raise FileNotFoundError(f"Could not find split file for '{split}' in {[str(c) for c in candidates]}")


def tokenize_sequence(sequence: str) -> List[int]:
    """Convert amino acid 1-letter sequence to token IDs."""
    return [AA_TO_ID.get(aa.upper(), AA_TO_ID["X"]) for aa in sequence]


def parse_cif_ca(cif_path: str) -> Tuple[str, List[Tuple[float, float, float]]]:
    """
    Fast native CIF parser extracting amino acid sequence and C-alpha (CA) coordinates.
    Returns:
        sequence (str): 1-letter amino acid sequence
        coordinates (list of (x, y, z)): 3D coordinates of CA atoms in Angstroms
    """
    sequence = []
    coords = []
    
    in_atom_site = False
    col_names = []
    
    with open(cif_path, "r", encoding="utf-8", errors="replace") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
                
            if line.startswith("loop_"):
                in_atom_site = False
                col_names = []
                continue
                
            if line.startswith("_atom_site."):
                in_atom_site = True
                col_names.append(line.split()[0])
                continue
                
            if in_atom_site:
                if line.startswith("#") or line.startswith("_"):
                    in_atom_site = False
                    continue
                    
                parts = line.split()
                if len(parts) >= len(col_names):
                    record = dict(zip(col_names, parts[:len(col_names)]))
                    atom_name = record.get("_atom_site.auth_atom_id") or record.get("_atom_site.label_atom_id")
                    
                    if atom_name == "CA":
                        res_name = record.get("_atom_site.auth_comp_id") or record.get("_atom_site.label_comp_id")
                        x = float(record.get("_atom_site.Cartn_x", 0.0))
                        y = float(record.get("_atom_site.Cartn_y", 0.0))
                        z = float(record.get("_atom_site.Cartn_z", 0.0))
                        
                        aa = THREE_TO_ONE.get(res_name, 'X')
                        sequence.append(aa)
                        coords.append((x, y, z))
                        
    return "".join(sequence), coords


def save_coords_to_pdb(
    coords: List[Tuple[float, float, float]],
    sequence: str,
    out_path: str,
    chain_id: str = "A",
    b_factors: Optional[List[float]] = None
) -> str:
    """
    Export 3D C-alpha coordinates and sequence to standard PDB format.
    Allows inspection in Mol*, PyMOL, ChimeraX, etc.
    """
    Path(out_path).parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w") as f:
        f.write("HEADER    PREDICTED PROTEIN STRUCTURE (SKELETON)\n")
        f.write("REMARK    GENERATED BY TEAM 2 (PSP) PIPELINE\n")
        for i, ((x, y, z), aa) in enumerate(zip(coords, sequence), start=1):
            res_name = ONE_TO_THREE.get(aa, "GLY")
            bfactor = b_factors[i - 1] if b_factors and i - 1 < len(b_factors) else 50.00
            # Standard PDB ATOM record format
            line = (
                f"ATOM  {i:5d}  CA  {res_name:3s} {chain_id:1s}{i:4d}    "
                f"{x:8.3f}{y:8.3f}{z:8.3f}  1.00{bfactor:6.2f}           C\n"
            )
            f.write(line)
        f.write("END\n")
    return out_path


# Optional PyTorch Dataset if torch is available
try:
    import torch
    from torch.utils.data import Dataset

    class ProteinStructureDataset(Dataset):
        """
        PyTorch Dataset for Protein Structure Prediction.
        Loads primary sequences and true C-alpha coordinates from binary cache (.pt)
        or directly from AFDB CIF files as fallback.
        """
        def __init__(
            self,
            split: str = "eval",
            splits_dir: str = "data/splits",
            structures_dir: str = "structures",
            processed_dir: str = "data/processed",
            use_cache: bool = True,
            max_len: int = 512,
            limit: Optional[int] = None
        ):
            self.split = split
            self.max_len = max_len
            self.from_cache = False
            self.cached_items = []
            self.items = []

            cache_path = Path(processed_dir) / f"{split}.pt"
            if use_cache and cache_path.exists():
                try:
                    payload = torch.load(cache_path, map_location="cpu", weights_only=False)
                    self.cached_items = payload.get("data", [])
                    if limit:
                        self.cached_items = self.cached_items[:limit]
                    self.from_cache = True
                except Exception as e:
                    print(f"Warning: Failed to load cache from {cache_path}: {e}. Falling back to CIF files.")
                    self.from_cache = False

            if not self.from_cache:
                self.structures_dir = Path(structures_dir) / split / "af"
                raw_ids = load_split(split, splits_dir=splits_dir)
                if limit:
                    raw_ids = raw_ids[:limit]
                    
                for pid in raw_ids:
                    fname = af_id_to_filename(pid)
                    if not fname:
                        continue
                    cif_path = self.structures_dir / fname
                    if cif_path.exists() and cif_path.stat().st_size > 0:
                        self.items.append((pid, cif_path))

        def __len__(self) -> int:
            return len(self.cached_items) if self.from_cache else len(self.items)

        def __getitem__(self, idx: int) -> Dict[str, Any]:
            if self.from_cache:
                item = self.cached_items[idx]
                pid = item["id"]
                seq = item["sequence"]
                coords_t = item["coords"]
                if len(seq) > self.max_len:
                    seq = seq[:self.max_len]
                    coords_t = coords_t[:self.max_len]
                coords_np = coords_t.numpy() if isinstance(coords_t, torch.Tensor) else np.array(coords_t, dtype=np.float32)
            else:
                pid, cif_path = self.items[idx]
                seq, coords = parse_cif_ca(str(cif_path))
                if len(seq) > self.max_len:
                    seq = seq[:self.max_len]
                    coords = coords[:self.max_len]
                coords_np = np.array(coords, dtype=np.float32)
            
            tokens = tokenize_sequence(seq)
            
            # Compute pairwise ground truth distance matrix (L, L)
            diff = coords_np[:, np.newaxis, :] - coords_np[np.newaxis, :, :]
            dist_matrix = np.sqrt(np.sum(diff ** 2, axis=-1))

            return {
                "id": pid,
                "sequence": seq,
                "length": len(seq),
                "tokens": torch.tensor(tokens, dtype=torch.long),
                "coords": torch.tensor(coords_np, dtype=torch.float32), # (L, 3)
                "dist_matrix": torch.tensor(dist_matrix, dtype=torch.float32) # (L, L)
            }

    def collate_protein_batch(batch: List[Dict[str, Any]]) -> Dict[str, Any]:
        """
        Collate variable-length protein sequences and coordinates with padding.
        """
        batch_size = len(batch)
        lengths = [item["length"] for item in batch]
        max_l = max(lengths)
        
        padded_tokens = torch.full((batch_size, max_l), PAD_IDX, dtype=torch.long)
        padded_coords = torch.zeros((batch_size, max_l, 3), dtype=torch.float32)
        padded_dist = torch.zeros((batch_size, max_l, max_l), dtype=torch.float32)
        mask = torch.zeros((batch_size, max_l), dtype=torch.bool)
        
        for i, item in enumerate(batch):
            l = item["length"]
            padded_tokens[i, :l] = item["tokens"]
            padded_coords[i, :l] = item["coords"]
            padded_dist[i, :l, :l] = item["dist_matrix"]
            mask[i, :l] = True
            
        return {
            "ids": [item["id"] for item in batch],
            "sequences": [item["sequence"] for item in batch],
            "lengths": torch.tensor(lengths, dtype=torch.long),
            "tokens": padded_tokens,     # (B, L_max)
            "coords": padded_coords,     # (B, L_max, 3)
            "dist_matrix": padded_dist,  # (B, L_max, L_max)
            "mask": mask                 # (B, L_max)
        }

except ImportError:
    pass
